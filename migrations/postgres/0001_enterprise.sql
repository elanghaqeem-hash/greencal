CREATE FUNCTION gcx_pg_revision_guard() RETURNS trigger LANGUAGE plpgsql AS $body$
BEGIN
 IF NEW.revision <> OLD.revision+1 OR NEW.tenant_id <> OLD.tenant_id OR NEW.id <> OLD.id OR NEW.created_by <> OLD.created_by OR NEW.created_at <> OLD.created_at THEN
   RAISE EXCEPTION 'invalid version or immutable identity field' USING ERRCODE='23514';
 END IF;
 IF TG_TABLE_NAME = 'gcx_records' AND (OLD.status IN ('approved','archived') OR NEW.kind<>OLD.kind) THEN
   RAISE EXCEPTION 'approved record frozen or immutable kind changed' USING ERRCODE='23514';
 ELSIF TG_TABLE_NAME = 'gcx_domain_records' AND (OLD.status IN ('approved','archived') OR NEW.kind<>OLD.kind) THEN
   RAISE EXCEPTION 'approved domain record frozen or immutable kind changed' USING ERRCODE='23514';
 ELSIF TG_TABLE_NAME = 'gcx_readiness_assessments' AND OLD.status='approved' THEN
   RAISE EXCEPTION 'approved readiness frozen' USING ERRCODE='23514';
 ELSIF TG_TABLE_NAME = 'gcx_book6_workpapers' AND NEW.status <> 'draft' THEN
   RAISE EXCEPTION 'Buku 6 workpaper must remain draft' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$body$;
