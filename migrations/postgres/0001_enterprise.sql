-- GreenCal CRMS Enterprise PostgreSQL schema v1 (2026-10-31).
-- Explicitly for an isolated, EMPTY, bank-approved PostgreSQL database.
-- Derived from the nine D1 enterprise migrations; no users, institutions,
-- sample records, scenario coefficients, factors or bank data are seeded.
-- Apply only with the dedicated migration command, never at request/build startup.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
CREATE TABLE IF NOT EXISTS gcx_pg_schema_migrations (
  version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
DO $$ BEGIN IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema=current_schema() AND table_name LIKE 'gcx_%' AND table_name <> 'gcx_pg_schema_migrations') THEN
 RAISE EXCEPTION 'Refusing to overwrite an existing GreenCal Enterprise PostgreSQL schema';
END IF; END $$;

