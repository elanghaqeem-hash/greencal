CREATE TRIGGER gcx_book6_workpapers_version AFTER INSERT OR UPDATE ON gcx_book6_workpapers FOR EACH ROW EXECUTE FUNCTION gcx_pg_version_event();

CREATE FUNCTION gcx_pg_insert_event() RETURNS trigger LANGUAGE plpgsql AS $body$
DECLARE actor TEXT; action TEXT; target TEXT; occurred TEXT;
BEGIN
 CASE TG_TABLE_NAME
 WHEN 'gcx_portfolio_batches' THEN actor:=NEW.owner_subject;action:='quant.portfolio_import';target:=NEW.id;occurred:=NEW.created_at;
 WHEN 'gcx_analytic_runs' THEN actor:=NEW.actor;action:='quant.'||NEW.kind;target:=NEW.id;occurred:=NEW.occurred_at;
 WHEN 'gcx_advanced_runs' THEN actor:=NEW.actor;action:='advanced.'||NEW.kind;target:=NEW.id;occurred:=NEW.created_at;
 WHEN 'gcx_portfolio_sources' THEN actor:=NEW.created_by;action:='quant.source_control';target:=NEW.source_sha256;occurred:=NEW.created_at;
 WHEN 'gcx_release_candidates' THEN actor:=NEW.created_by;action:='release.created';target:=NEW.id;occurred:=NEW.created_at;
 WHEN 'gcx_release_assignments' THEN actor:=NEW.appointed_by;action:='release.assigned';target:=NEW.function;occurred:=NEW.appointed_at;
 WHEN 'gcx_release_reviews' THEN actor:=NEW.reviewer_subject;action:='release.'||NEW.outcome;target:=NEW.candidate_id||':'||NEW.function;occurred:=NEW.reviewed_at;
 WHEN 'gcx_verified_source_candidates' THEN actor:=NEW.submitted_by;action:='source.candidate';target:=NEW.id;occurred:=NEW.submitted_at;
 WHEN 'gcx_source_attestations' THEN actor:=NEW.reviewer_subject;action:='source.review.'||NEW.outcome;target:=NEW.source_id||':'||NEW.reviewer_function;occurred:=NEW.reviewed_at;
 ELSE RAISE EXCEPTION 'unexpected event table %',TG_TABLE_NAME;
 END CASE;
