CREATE FUNCTION gcx_pg_version_event() RETURNS trigger LANGUAGE plpgsql AS $body$
DECLARE action TEXT;
BEGIN
 CASE TG_TABLE_NAME
 WHEN 'gcx_records' THEN
  INSERT INTO gcx_record_versions(tenant_id,record_id,revision,kind,title,payload,status,actor,checked_by,approved_by,reason,occurred_at) VALUES(NEW.tenant_id,NEW.id,NEW.revision,NEW.kind,NEW.title,NEW.payload,NEW.status,NEW.updated_by,NEW.checked_by,NEW.approved_by,NEW.reason,NEW.updated_at);
  action := CASE WHEN TG_OP='INSERT' THEN 'record.created' ELSE 'record.'||NEW.status END;
 WHEN 'gcx_domain_records' THEN
  INSERT INTO gcx_domain_versions(tenant_id,record_id,revision,kind,title,payload,status,actor,checked_by,approved_by,reason,occurred_at) VALUES(NEW.tenant_id,NEW.id,NEW.revision,NEW.kind,NEW.title,NEW.payload,NEW.status,NEW.updated_by,NEW.checked_by,NEW.approved_by,NEW.reason,NEW.updated_at);
  action := CASE WHEN TG_OP='INSERT' THEN 'domain.created' ELSE 'domain.'||NEW.status END;
 WHEN 'gcx_readiness_assessments' THEN
  INSERT INTO gcx_readiness_versions(tenant_id,assessment_id,revision,title,payload,status,actor,checked_by,approved_by,reason,occurred_at) VALUES(NEW.tenant_id,NEW.id,NEW.revision,NEW.title,NEW.payload,NEW.status,NEW.updated_by,NEW.checked_by,NEW.approved_by,NEW.reason,NEW.updated_at);
  action := CASE WHEN TG_OP='INSERT' THEN 'readiness.created' ELSE 'readiness.'||NEW.status END;
 WHEN 'gcx_book6_workpapers' THEN
  INSERT INTO gcx_book6_versions(tenant_id,workpaper_id,revision,payload_json,actor,occurred_at) VALUES(NEW.tenant_id,NEW.id,NEW.revision,NEW.payload_json,NEW.updated_by,NEW.updated_at);
  action := CASE WHEN TG_OP='INSERT' THEN 'book6.draft.created' ELSE 'book6.draft.'||'updated' END;
 ELSE RAISE EXCEPTION 'unexpected version table %',TG_TABLE_NAME;
 END CASE;
 INSERT INTO gcx_events(tenant_id,actor,action,target,occurred_at)
 VALUES(NEW.tenant_id,NEW.updated_by,action,NEW.id,NEW.updated_at);
 RETURN NEW;
END;
$body$;
CREATE TRIGGER gcx_records_version AFTER INSERT OR UPDATE ON gcx_records FOR EACH ROW EXECUTE FUNCTION gcx_pg_version_event();
CREATE TRIGGER gcx_domain_records_version AFTER INSERT OR UPDATE ON gcx_domain_records FOR EACH ROW EXECUTE FUNCTION gcx_pg_version_event();
