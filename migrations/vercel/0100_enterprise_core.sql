-- GreenCal Enterprise PostgreSQL baseline. Dedicated, empty institution DB only.
-- Manual PostgreSQL-native counterpart to Cloudflare D1 migrations 0001-0003.
-- Apply 0100 and 0101 together in one reviewed release; never reuse public AI DB.
BEGIN;
CREATE TABLE gcx_institutions (
 id TEXT PRIMARY KEY, name TEXT NOT NULL,
 institution_type TEXT NOT NULL CHECK(institution_type IN ('BUS','UUS','BUK','LJK')),
 currency TEXT NOT NULL CHECK(length(currency)=3),
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
 created_at TEXT NOT NULL
);
CREATE TABLE gcx_memberships (
 tenant_id TEXT NOT NULL REFERENCES gcx_institutions(id), subject TEXT NOT NULL,
 email TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN
 ('super_administrator','institution_administrator','crms_project_administrator',
 'data_maker','risk_analyst','climate_model_analyst','checker','approver',
 'risk_management_head','compliance_reviewer','sharia_governance_reviewer',
 'executive_viewer','internal_auditor','external_auditor')),
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
 PRIMARY KEY(tenant_id,subject)
);
CREATE TABLE gcx_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id TEXT NOT NULL REFERENCES gcx_institutions(id),
 actor TEXT NOT NULL, action TEXT NOT NULL,
 target TEXT NOT NULL, occurred_at TEXT NOT NULL
);
CREATE INDEX gcx_events_tenant ON gcx_events(tenant_id,id DESC);
CREATE FUNCTION gcx_immutable() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'immutable evidence: mutation prohibited'; END; $$;
CREATE TRIGGER gcx_events_immutable BEFORE UPDATE OR DELETE ON gcx_events
 FOR EACH ROW EXECUTE FUNCTION gcx_immutable();

CREATE TABLE gcx_records (
 tenant_id TEXT NOT NULL REFERENCES gcx_institutions(id), id TEXT NOT NULL,
 kind TEXT NOT NULL CHECK(kind IN ('risk','factor','emission','regulatory_document','requirement')),
 title TEXT NOT NULL, payload TEXT NOT NULL CHECK(payload IS JSON),
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','submitted','checked','approved','rejected','archived')),
 revision INTEGER NOT NULL DEFAULT 1 CHECK(revision>0),
 created_by TEXT NOT NULL,updated_by TEXT NOT NULL,checked_by TEXT,approved_by TEXT,
 reason TEXT NOT NULL DEFAULT '',created_at TEXT NOT NULL,updated_at TEXT NOT NULL,
 PRIMARY KEY(tenant_id,id),
 FOREIGN KEY(tenant_id,created_by) REFERENCES gcx_memberships(tenant_id,subject),
 FOREIGN KEY(tenant_id,updated_by) REFERENCES gcx_memberships(tenant_id,subject),
 CHECK(checked_by IS NULL OR checked_by<>created_by),
 CHECK(approved_by IS NULL OR (approved_by<>created_by AND approved_by<>checked_by)),
 CHECK(status<>'checked' OR checked_by IS NOT NULL),
 CHECK(status<>'approved' OR (checked_by IS NOT NULL AND approved_by IS NOT NULL))
);
CREATE INDEX gcx_records_list ON gcx_records(tenant_id,kind,status,updated_at DESC);
CREATE TABLE gcx_record_versions(
 tenant_id TEXT NOT NULL,record_id TEXT NOT NULL,revision INTEGER NOT NULL,
 kind TEXT NOT NULL,title TEXT NOT NULL,payload TEXT NOT NULL CHECK(payload IS JSON),
 status TEXT NOT NULL,actor TEXT NOT NULL,checked_by TEXT,approved_by TEXT,
 reason TEXT NOT NULL,occurred_at TEXT NOT NULL,
 PRIMARY KEY(tenant_id,record_id,revision),
 FOREIGN KEY(tenant_id,record_id) REFERENCES gcx_records(tenant_id,id)
);
CREATE FUNCTION gcx_records_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.revision<>OLD.revision+1 OR NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
    OR NEW.id IS DISTINCT FROM OLD.id OR NEW.kind IS DISTINCT FROM OLD.kind
    OR NEW.created_by IS DISTINCT FROM OLD.created_by
    OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
  RAISE EXCEPTION 'invalid record revision';
 END IF;
 IF OLD.status IN ('approved','archived') THEN
  RAISE EXCEPTION 'record is frozen; create a superseding record';
 END IF;
 RETURN NEW;
END; $$;
CREATE FUNCTION gcx_records_capture() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO gcx_record_versions
  (tenant_id,record_id,revision,kind,title,payload,status,actor,
   checked_by,approved_by,reason,occurred_at)
 VALUES(NEW.tenant_id,NEW.id,NEW.revision,NEW.kind,NEW.title,NEW.payload,NEW.status,
  NEW.updated_by,NEW.checked_by,NEW.approved_by,NEW.reason,NEW.updated_at);
 INSERT INTO gcx_events(tenant_id,actor,action,target,occurred_at)
 VALUES(NEW.tenant_id,NEW.updated_by,
  CASE WHEN TG_OP='INSERT' THEN 'record.created' ELSE 'record.'||NEW.status END,
  NEW.id,NEW.updated_at);
 RETURN NEW;
END; $$;
CREATE TRIGGER gcx_records_guard_update BEFORE UPDATE ON gcx_records
 FOR EACH ROW EXECUTE FUNCTION gcx_records_guard();
CREATE TRIGGER gcx_records_audit AFTER INSERT OR UPDATE ON gcx_records
 FOR EACH ROW EXECUTE FUNCTION gcx_records_capture();
CREATE TRIGGER gcx_records_immutable_delete BEFORE DELETE ON gcx_records
 FOR EACH ROW EXECUTE FUNCTION gcx_immutable();
CREATE TRIGGER gcx_record_versions_immutable BEFORE UPDATE OR DELETE ON gcx_record_versions
 FOR EACH ROW EXECUTE FUNCTION gcx_immutable();

